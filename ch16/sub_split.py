import re

text = "연락처: 010-1234-5678, 010-9876-5432"

# 찾은 부분을 정해진 문자열로 바꾼다
print(re.sub(r"\d{4}-\d{4}", "****-****", text))

# \1, \3은 첫째, 셋째 그룹에 맞은 부분이다
print(re.sub(r"(\d{3})-(\d{4})-(\d{4})", r"\1-****-\3", text))
print(re.sub(r"(\d{4})-(\d{2})-(\d{2})", r"\3/\2/\1", "2026-11-02"))

print(re.sub(r"\s+", " ", "공백이   여러  개\t섞인   문장"))

# 여러 가지 구분자로 나눈다
print(re.split(r"\s*[,;/]\s*", "사과, 배;감 / 귤"))
